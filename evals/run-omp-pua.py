def _canonical_json(value: Any) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def _private_write(path: Path, text: str) -> None:
    """Write a 0600 evidence artifact inside the already-0700 run directory."""
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
    except BaseException:
        with contextlib.suppress(FileNotFoundError):
            path.unlink()
        raise


def _private_json(path: Path, value: Any) -> None:
    _private_write(path, json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def _reject_links_and_special_files(root: Path) -> None:
    """Reject symlinks and non-regular sources before copying an eval fixture."""
    if root.is_symlink():
        raise ValueError(f"symlink source is not permitted: {root}")
    for base, dirs, files in os.walk(root, followlinks=False):
        base_path = Path(base)
        retained_dirs: list[str] = []
        for name in dirs:
            item = base_path / name
            if item.is_symlink():
                raise ValueError(f"symlink source is not permitted: {item}")
            if not item.is_dir():
                raise ValueError(f"non-directory entry in source tree: {item}")
            retained_dirs.append(name)
        dirs[:] = retained_dirs
        for name in files:
            item = base_path / name
            mode = item.lstat().st_mode
            if stat.S_ISLNK(mode) or not stat.S_ISREG(mode):
                raise ValueError(f"only regular files are permitted in source tree: {item}")


def tree_manifest(root: Path) -> dict[str, Any]:
    """Hash a regular-file tree using relative names, sizes, and SHA-256 values."""
    root = root.resolve(strict=True)
    if not root.is_dir():
        raise ValueError(f"expected a directory: {root}")
    _reject_links_and_special_files(root)
    files: list[dict[str, Any]] = []
    for base, dirs, names in os.walk(root, followlinks=False):
        dirs.sort()
        for name in sorted(names):
            path = Path(base) / name
            rel = path.relative_to(root).as_posix()
            files.append({"path": rel, "bytes": path.stat().st_size, "sha256": sha256_file(path)})
    body = {"schema_version": 1, "files": files}
    return {**body, "tree_sha256": sha256_bytes(_canonical_json(body))}


def _manifest_after_run(root: Path) -> tuple[dict[str, Any] | None, str | None]:
    """Turn a model-caused source deletion/corruption into recorded failure."""
    try:
        return tree_manifest(root), None
    except (OSError, ValueError, UnicodeError) as error:
        # A type is enough to prove the check could not complete; paths and raw
        # exception text are unnecessary evidence and could disclose host data.
        return None, type(error).__name__


def _reject_overlapping_trees(source: Path, destination: Path) -> None:
    source, destination = source.resolve(), destination.resolve()
    if source == destination or source in destination.parents or destination in source.parents:
        raise ValueError("source and destination trees must not overlap")


def _copy_tree(source: Path, destination: Path, *, read_only: bool) -> None:
    """Copy a previously validated regular-file tree; never follow a symlink."""
    _reject_overlapping_trees(source, destination)
    _reject_links_and_special_files(source)
    destination.mkdir(mode=0o700)
    for base, dirs, names in os.walk(source, followlinks=False):
        source_base = Path(base)
        rel_base = source_base.relative_to(source)
        target_base = destination / rel_base
        target_base.mkdir(exist_ok=True, mode=0o700)
        for name in sorted(dirs):
            (target_base / name).mkdir(exist_ok=True, mode=0o700)
        for name in sorted(names):
            source_file = source_base / name
            target_file = target_base / name
            with source_file.open("rb") as input_handle, target_file.open("xb") as output_handle:
                shutil.copyfileobj(input_handle, output_handle, length=1024 * 1024)
            os.chmod(target_file, 0o400 if read_only else 0o600)
    if read_only:
        # This is accidental-mutation resistance, not a security boundary: the
        # current user can chmod it again.  Post-run manifest comparison is the
        # evidence gate.
        for base, dirs, _ in os.walk(destination, topdown=False, followlinks=False):
            for name in dirs:
                os.chmod(Path(base) / name, 0o500)
        os.chmod(destination, 0o500)


def _skill_name(skill_file: Path) -> str:
    if skill_file.name != "SKILL.md":
        raise ValueError("--skill-source must name an actual SKILL.md file")
    text = skill_file.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError("skill source needs YAML frontmatter")
    closing = text.find("\n---", 4)
    if closing < 0:
        raise ValueError("skill source frontmatter is not closed")
    match = _SKILL_NAME.search(text[4:closing])
    if not match:
        raise ValueError("skill source frontmatter has no simple name")
    return match.group(1)


def _validate_tools(raw: str) -> list[str]:
    tools = [item.strip().lower() for item in raw.split(",") if item.strip()]
    if not tools:
        raise ValueError("--tools must include at least read")
    unknown = sorted(set(tools) - _ALLOWED_TOOLS)
    if unknown:
        raise ValueError(f"unsupported tool(s): {', '.join(unknown)}; allowed: {', '.join(sorted(_ALLOWED_TOOLS))}")
    if "read" not in tools:
        raise ValueError("--tools must include read for native skill proof")
    return list(dict.fromkeys(tools))


def _catalog_evidence(catalog_path: Path | None, selector: str) -> dict[str, Any]:
    if catalog_path is None:
        return {
            "checked": False,
            "membership": "not_checked",
            "meaning": "no local catalog was supplied; this is not availability or entitlement evidence",
        }
    raw = catalog_path.read_bytes()
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError as error:
        raise ValueError(f"model catalog is not JSON: {error.msg}") from error
    records = parsed.get("models") if isinstance(parsed, dict) else None
    if not isinstance(records, list):
        raise ValueError("model catalog must be an object with a models array")
    matches = [record for record in records if isinstance(record, dict) and record.get("selector") == selector]
    if not matches:
        raise ValueError(f"exact selector is absent from supplied local catalog: {selector}")
    provider, model_id = selector.split("/", 1)
    component_consistent = all(
        record.get("provider") in {None, provider} and record.get("id") in {None, model_id} for record in matches
    )
    if not component_consistent:
        raise ValueError(f"catalog selector/provider/id inconsistency for {selector}")
    return {
        "checked": True,
        "catalog_sha256": sha256_bytes(raw),
        "exact_selector_match_count": len(matches),
        "membership": "local_catalog_exact_match",
        "meaning": "local OMP catalog membership only; not service availability, routing, or entitlement proof",
    }


def _read_version(binary: Path) -> str | None:
    try:
        result = subprocess.run(
            [str(binary), "--version"],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            timeout=15,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    text = result.stdout.decode("utf-8", "replace").strip()
    # v18.1.13's installed binary prints ``omp/18.1.13``; older/help forms
    # may use ``omp v18.1.13``.  Normalize both without accepting arbitrary
    # surrounding output as a version claim.
    match = re.search(r"\bomp(?:\s+v?|/)([0-9][^\s]*)", text)
    return f"omp/{match.group(1)}" if result.returncode == 0 and match else None


def _source_package_version() -> str | None:
    package = Path.home() / ".bun/install/global/node_modules/@oh-my-pi/pi-coding-agent/package.json"
    try:
        data = json.loads(package.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    value = data.get("version") if isinstance(data, dict) else None
    return value if isinstance(value, str) else None


def _probe_overlay(binary: Path, overlay: Path, destination: Path) -> dict[str, Any]:
    """Verify accepted effective settings without auth, a model, or global state.

    v18.1.13's ``config`` subcommand does not honor its CLI ``--config`` flag in
    this installation, so this probe uses the runtime-supported PI_CONFIG_FILES
    overlay explicitly.  The actual OMP child receives the same single env
    overlay and also the documented --config argument for main-session loading.
    """
    probe = destination / "schema-probe"
    probe.mkdir(mode=0o700)
    home = probe / "home"
    state = probe / "agent"
    home.mkdir(mode=0o700)
    state.mkdir(mode=0o700)
    env = {
        "PATH": os.environ.get("PATH", ""),
        "HOME": str(home),
        "PI_CODING_AGENT_DIR": str(state),
        "PI_CONFIG_FILES": str(overlay),
        "LANG": "C",
        "LC_ALL": "C",
    }
    results: dict[str, Any] = {}
    all_passed = True
    for key, expected in OVERLAY_EXPECTATIONS.items():
        try:
            completed = subprocess.run(
                [str(binary), "config", "get", key, "--json"],
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                env=env,
                timeout=20,
                check=False,
            )
            payload = json.loads(completed.stdout.decode("utf-8", "replace")) if completed.returncode == 0 else {}
            observed = payload.get("value") if isinstance(payload, dict) else None
            passed = completed.returncode == 0 and observed == expected
            results[key] = {
                "expected": expected,
                "observed_type": type(observed).__name__ if completed.returncode == 0 else None,
                "matched": passed,
                "exit_code": completed.returncode,
            }
        except (OSError, subprocess.TimeoutExpired, json.JSONDecodeError):
            passed = False
            results[key] = {"expected": expected, "observed_type": None, "matched": False, "exit_code": None}
        all_passed = all_passed and passed
    return {
        "method": "isolated_omp_config_get_with_PI_CONFIG_FILES",
        "model_or_login_called": False,
        "all_expected_controls_effective": all_passed,
        "controls": results,
        "limitation": "validates settings resolution, not a provider request or complete plugin-isolation semantics",
    }


def _restricted_environment(overlay: Path, inherit_auth_env: bool) -> tuple[dict[str, str], list[str]]:
    """Create child environment without serializing any values into evidence."""
    env = dict(os.environ)
    removed: list[str] = []
    if not inherit_auth_env:
        for key in list(env):
            if _SECRET_ENV.search(key):
                removed.append(key)
                env.pop(key, None)
    # Set, rather than append, to avoid a user-level PI_CONFIG_FILES overlay.
    env["PI_CONFIG_FILES"] = str(overlay)
    return env, sorted(removed)


def _stop_group(process: subprocess.Popen[bytes]) -> None:
    with contextlib.suppress(ProcessLookupError):
        os.killpg(process.pid, signal.SIGTERM)
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        with contextlib.suppress(ProcessLookupError):
            os.killpg(process.pid, signal.SIGKILL)
        with contextlib.suppress(subprocess.TimeoutExpired):
            process.wait(timeout=5)


def _event_identity_or_refusal(event: dict[str, Any]) -> tuple[str | None, bool]:
    """Extract only a structural identity/refusal signal for early stop."""
    if event.get("type") == "system" and str(event.get("subtype", "")).startswith("model_refusal_"):
        return None, True
    message = event.get("message")
    if not isinstance(message, dict) and isinstance(event.get("role"), str):
        message = event
    if not isinstance(message, dict) or message.get("role") != "assistant":
        return None, False
    provider, model = message.get("provider"), message.get("model")
    if isinstance(provider, str) and isinstance(model, str) and provider and model and "/" not in provider and "/" not in model:
        return f"{provider}/{model}", False
    return "<missing-or-malformed-runtime-identity>", False


def _watch_process(
    process: subprocess.Popen[bytes],
    expected_selector: str,
    timeout_seconds: int,
    max_stream_bytes: int,
) -> tuple[int | None, bool, str | None, bytes]:
    """Drain JSON-mode stdout in memory and fail fast on visible substitution.

    This avoids a durable raw stream altogether.  It is still not a promise that
    an untrusted model cannot emit a secret; the buffer is capped, reduced to
    safe evidence immediately after exit, and then released.
    """
    if process.stdout is None:
        raise RuntimeError("OMP stdout pipe was not created")
    deadline = time.monotonic() + timeout_seconds
    partial = b""
    captured = bytearray()
    selector = selectors.DefaultSelector()
    os.set_blocking(process.stdout.fileno(), False)
    selector.register(process.stdout, selectors.EVENT_READ)
    stream_open = True
    while True:
        events = selector.select(timeout=0.10)
        for key, _ in events:
            try:
                chunk = os.read(key.fileobj.fileno(), 64 * 1024)
            except BlockingIOError:
                continue
            if not chunk:
                with contextlib.suppress(Exception):
                    selector.unregister(key.fileobj)
                stream_open = False
                continue
            if len(captured) + len(chunk) > max_stream_bytes:
                _stop_group(process)
                selector.close()
                return process.poll(), False, "stream_size_limit", bytes(captured)
            captured.extend(chunk)
            partial += chunk
            lines = partial.split(b"\n")
            partial = lines.pop()
            for raw in lines:
                try:
                    event = json.loads(raw.decode("utf-8"))
                except (UnicodeDecodeError, json.JSONDecodeError):
                    continue
                if not isinstance(event, dict):
                    continue
                actual, refused = _event_identity_or_refusal(event)
                if refused:
                    _stop_group(process)
                    selector.close()
                    return process.poll(), False, "model_refusal_event", bytes(captured)
                if actual is not None and actual != expected_selector:
                    _stop_group(process)
                    selector.close()
                    return process.poll(), False, f"unexpected_model:{actual}", bytes(captured)
        if process.poll() is not None and not stream_open:
            selector.close()
            return process.returncode, False, None, bytes(captured)
        if time.monotonic() >= deadline:
            _stop_group(process)
            selector.close()
            return process.poll(), True, "timeout", bytes(captured)


def _build_prompt(user_prompt: str, skill_name: str) -> str:
    # Do not inject the source skill into the prompt.  It must be discovered by
    # OMP's native Agent Plugin route; the tool call evidence decides success.
    return f"""[OMP evaluation control]
Work only on the current isolated task workspace. Before any business action, call the native OMP read tool with the exact path `skill://{skill_name}`. Do not substitute a local or absolute file path. If that native resource is unavailable, stop and report that failure; do not claim the skill loaded from this instruction text. Do not read credentials, change global configuration, install software, access a browser, or create a subagent. Keep all requested task artifacts inside the task workspace.

[Evaluation task]
{user_prompt}
"""


def _remap_task_paths(user_prompt: str, source_task_root: Path, execution_task_root: Path) -> tuple[str, int]:
    """Map only absolute paths under the copied fixture into the execution copy.

    A fixture prompt often names ``/original/fixture/file``.  Passing it through
    unchanged would make the model's natural-language task contradict OMP's
    ``--cwd`` and invite edits to the protected source fixture.  This is a
    lexical remap, intentionally limited to the exact source-root prefix and a
    path boundary; siblings such as ``<root>-backup`` are not altered.
    """
    effective = str(execution_task_root)
    # macOS commonly presents /var while realpath uses /private/var.  Treat
    # both spellings of *this exact fixture root* as aliases, never a broad
    # prefix such as /var or /private.  The command's lexical --cwd spelling is
    # used for the replacement so prompt and execution context agree.
    aliases = {str(source_task_root.absolute())}
    with contextlib.suppress(OSError):
        aliases.add(str(source_task_root.resolve(strict=False)))
    remapped = user_prompt
    replacements = 0
    for original in sorted(aliases, key=len, reverse=True):
        # ``/fixture`` may be followed by a child slash, punctuation/whitespace,
        # or end-of-string, but not another filename character.
        matcher = re.compile(re.escape(original) + r"(?=$|/|[^A-Za-z0-9._~-])")
        remapped, count = matcher.subn(effective, remapped)
        replacements += count
    return remapped, replacements


def _prompt_evidence(original_prompt: str, effective_prompt: str, controlled_prompt: str, remap_count: int) -> dict[str, Any]:
    """Persist only hashes/lengths for prompt provenance, never prompt text."""
    return {
        "original_sha256": sha256_bytes(original_prompt.encode("utf-8")),
        "original_bytes": len(original_prompt.encode("utf-8")),
        "effective_sha256": sha256_bytes(effective_prompt.encode("utf-8")),
        "effective_bytes": len(effective_prompt.encode("utf-8")),
        "controlled_sha256": sha256_bytes(controlled_prompt.encode("utf-8")),
        "controlled_bytes": len(controlled_prompt.encode("utf-8")),
        "absolute_paths_remapped_from_source_fixture": remap_count,
        "content_retained": False,
    }


def _make_plugin(destination: Path, skill_source: Path, skill_name: str) -> Path:
    plugin = destination / "plugin"
    plugin.mkdir(mode=0o700)
    manifest = {
        "$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
        "name": "pua-evaluation-fixture",
        "version": "0.0.0",
        "description": "Ephemeral isolated PUA evaluation fixture",
    }
    _private_json(plugin / "plugin.json", manifest)
    skills = plugin / "skills"
    skills.mkdir(mode=0o700)
    target = skills / skill_name
    _copy_tree(skill_source.parent, target, read_only=True)
    return target / "SKILL.md"


def _plan(args: argparse.Namespace, *, omp_binary: Path, prompt: str, skill_source: Path, skill_name: str,
          task_source: Path, task_prompt_root: Path, task_destination: Path, tools: list[str], catalog: dict[str, Any]) -> dict[str, Any]:
    source_tree = tree_manifest(skill_source.parent)
    task_tree = tree_manifest(task_source)
    effective_prompt, remap_count = _remap_task_paths(prompt, task_prompt_root, task_destination)
    controlled_prompt = _build_prompt(effective_prompt, skill_name)
    return {
        "schema_version": RUNNER_SCHEMA_VERSION,
        "live": False,
        "requested_model": args.model,
        "selector_policy": "full provider/model required; aliases and fuzzy matching rejected by runner",
        "local_catalog": catalog,
        "omp_binary": {"path": str(omp_binary), "sha256": sha256_file(omp_binary)},
        "installed_source_package_version": _source_package_version(),
        "source_package_is_not_binary_authority": True,
        "prompt": _prompt_evidence(prompt, effective_prompt, controlled_prompt, remap_count),
        "skill": {"name": skill_name, "source_tree": source_tree, "marker_required": "PUA-RUNTIME-CONTRACT:START"},
        "task_fixture": {"source_tree": task_tree, "copied_to_new_run_directory": True},
        "tools": tools,
        "timeout_seconds": args.timeout,
        "max_stream_bytes": args.max_stream_bytes,
        "native_loading_requirement": "read(skill://pua) + matching result marker + resolvedPath to isolated plugin copy",
        "control_overlay": {"expected": OVERLAY_EXPECTATIONS, "transport": "PI_CONFIG_FILES plus --config for main session"},
        "global_configuration_changed_by_runner": False,
        "stdin": "closed",
        "run_only_note": "--run is required before invoking OMP or creating the run directory",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True, help="exact provider/model selector, e.g. xai-oauth/grok-4.6")
    parser.add_argument("--cwd", type=Path, required=True,
                        help="existing fixture directory; copied to a new isolated task directory")
    parser.add_argument("--prompt-file", type=Path, required=True)
    parser.add_argument("--run-dir", type=Path, required=True,
                        help="must not exist; a new owner-only evidence directory is created only with --run")
    parser.add_argument("--skill-source", type=Path, required=True,
                        help="absolute path to the source SKILL.md copied into an ephemeral Agent Plugin")
    parser.add_argument("--tools", default="read,glob,grep,write,edit,bash")
    parser.add_argument("--timeout", type=int, default=600)
    parser.add_argument("--max-stream-bytes", type=int, default=16 * 1024 * 1024)
    parser.add_argument("--thinking", choices=sorted(_THINKING_LEVELS), default="high")
    parser.add_argument("--approval-mode", choices=("always-ask", "write", "yolo"), default="write")
    parser.add_argument("--allow-yolo", action="store_true", help="required before passing --approval-mode yolo")
    parser.add_argument("--inherit-auth-env", action="store_true",
                        help="explicitly retain token-like environment variables; values are never logged")
    parser.add_argument("--model-catalog", type=Path,
                        help="optional local OMP models JSON; exact selector membership is checked offline")
    parser.add_argument("--omp-binary", type=Path, default=Path(shutil.which("omp") or "omp"))
    parser.add_argument("--run", action="store_true")
    args = parser.parse_args()

    if not _SELECTOR.fullmatch(args.model):
        parser.error("--model must be an exact provider/model selector, not a fuzzy alias or role")
    if args.timeout <= 0 or args.max_stream_bytes <= 0:
        parser.error("--timeout and --max-stream-bytes must be positive")
    if args.approval_mode == "yolo" and not args.allow_yolo:
        parser.error("--approval-mode yolo requires explicit --allow-yolo")
    if args.allow_yolo and args.approval_mode != "yolo":
        parser.error("--allow-yolo only applies with --approval-mode yolo")
    if not args.skill_source.is_absolute():
        parser.error("--skill-source must be absolute so evidence cannot depend on launch cwd")

    try:
        omp_binary = args.omp_binary.resolve(strict=True)
        if not omp_binary.is_file():
            raise ValueError(f"OMP binary is not a regular file: {omp_binary}")
        skill_source = args.skill_source.resolve(strict=True)
        if args.skill_source.is_symlink() or args.skill_source.parent.is_symlink() or not skill_source.is_file():
            raise ValueError("--skill-source must be a non-symlink regular file")
        skill_name = _skill_name(skill_source)
        if skill_name != "pua":
            raise ValueError(f"this PUA runner requires source frontmatter name pua, not {skill_name!r}")
        if "PUA-RUNTIME-CONTRACT:START" not in skill_source.read_text(encoding="utf-8"):
            raise ValueError("skill source lacks the required PUA runtime marker")
        task_prompt_root = args.cwd.absolute()
        task_source = task_prompt_root.resolve(strict=True)
        if args.cwd.is_symlink() or not task_source.is_dir():
            raise ValueError("--cwd must be an existing non-symlink fixture directory")
        _reject_overlapping_trees(task_source, args.run_dir)
        _reject_overlapping_trees(skill_source.parent, args.run_dir)
        prompt = args.prompt_file.read_text(encoding="utf-8")
        tools = _validate_tools(args.tools)
        catalog = _catalog_evidence(args.model_catalog.resolve(strict=True) if args.model_catalog else None, args.model)
    except (OSError, ValueError, UnicodeDecodeError) as error:
        parser.error(str(error))

    planned_destination = args.run_dir.absolute()
    plan = _plan(args, omp_binary=omp_binary, prompt=prompt, skill_source=skill_source, skill_name=skill_name,
                 task_source=task_source, task_prompt_root=task_prompt_root,
                 task_destination=planned_destination / "task", tools=tools, catalog=catalog)
    if not args.run:
        print(json.dumps(plan, ensure_ascii=False, indent=2))
        return 0

    destination = planned_destination
    if destination.exists():
        parser.error("--run-dir must not already exist; refusing to overwrite prior evidence")
    old_umask = os.umask(0o077)
    try:
        destination.mkdir(parents=True, mode=0o700)
        os.chmod(destination, 0o700)
        overlay = destination / "omp-overlay.yml"
        _private_write(overlay, OVERLAY_YAML)
        plugin_skill = _make_plugin(destination, skill_source, skill_name)
        task_destination = destination / "task"
        _copy_tree(task_source, task_destination, read_only=False)
        effective_prompt, remap_count = _remap_task_paths(prompt, task_prompt_root, task_destination)
        controlled_prompt = _build_prompt(effective_prompt, skill_name)
        prompt_evidence = _prompt_evidence(prompt, effective_prompt, controlled_prompt, remap_count)
        if prompt_evidence != plan["prompt"]:
            raise RuntimeError("planned and effective prompt provenance differ")

        source_before = tree_manifest(skill_source.parent)
        plugin_before = tree_manifest(plugin_skill.parent)
        task_source_before = tree_manifest(task_source)
        if source_before["tree_sha256"] != plugin_before["tree_sha256"]:
            raise RuntimeError("isolated plugin copy does not match the supplied skill source")
        _private_json(destination / "skill-source-manifest.json", source_before)
        _private_json(destination / "task-source-manifest.json", task_source_before)
        manifest_record_sha = sha256_file(destination / "skill-source-manifest.json")

        cli_version = _read_version(omp_binary)
        source_version = _source_package_version()
        schema_probe = _probe_overlay(omp_binary, overlay, destination)
        invocation = {
            **plan,
            "live": True,
            "omp_binary": {**plan["omp_binary"], "reported_version": cli_version},
            "installed_source_package_version": source_version,
            "installed_source_version_matches_cli": (source_version == cli_version.removeprefix("omp/") if cli_version else None),
            "run_directory": str(destination),
            "task_cwd": str(task_destination),
            "plugin_skill_source": str(plugin_skill),
            "skill_manifest_record_sha256": manifest_record_sha,
            "skill_source_before_tree_sha256": source_before["tree_sha256"],
            "isolated_plugin_before_tree_sha256": plugin_before["tree_sha256"],
            "schema_probe": schema_probe,
            "prompt": prompt_evidence,
            "auth_environment": {
                "inherit_auth_env": args.inherit_auth_env,
                "values_logged": False,
                "default_behavior": "remove token-like environment variable names before model run" if not args.inherit_auth_env else "explicitly retained by caller",
            },
            "security_boundary": {
                "tool_allowlist": tools,
                "workspace_copy": str(task_destination),
                "not_an_os_sandbox": True,
                "global_omp_cache_or_auth_side_effects_prevented": False,
            },
        }
        _private_json(destination / "invocation.json", invocation)

        if not schema_probe["all_expected_controls_effective"]:
            summary = {
                "schema_version": RUNNER_SCHEMA_VERSION,
                "run_passed": False,
                "transport_run_passed": False,
                "behavioral_verdict": "ungraded_by_omp_adapter",
                "failure": "overlay_controls_not_effective",
                "schema_probe": schema_probe,
                "model_identity": {
                    "requested_selector": args.model,
                    "runtime_event_observed": False,
                    "provider_server_receipt_observed": False,
                },
            }
            _private_json(destination / "summary.json", summary)
            print(json.dumps({"run_passed": False, "failure": summary["failure"], "run_dir": str(destination)}, ensure_ascii=False))
            return 2

        command = [
            str(omp_binary),
            "--cwd", str(task_destination),
            "--config", str(overlay),
            "--plugin-dir", str(destination / "plugin"),
            "--model", args.model,
            "--mode", "json",
            "--no-session",
            "--no-lsp",
            "--no-pty",
            "--no-extensions",
            "--no-rules",
            "--no-title",
            "--no-prewalk",
            "--skills", skill_name,
            "--tools", ",".join(tools),
            "--thinking", args.thinking,
            "--max-time", str(args.timeout),
            "--approval-mode", args.approval_mode,
            "--print",
            controlled_prompt,
        ]
        child_env, removed_env_names = _restricted_environment(overlay, args.inherit_auth_env)
        # Neither values nor environment-variable names are persisted: even a
        # name can disclose an account/provider posture unrelated to this test.
        invocation_update = {
            "command_redacted": [
                "omp", "--cwd", "<isolated-task>", "--config", "<per-run-overlay>", "--plugin-dir", "<isolated-plugin>",
                "--model", args.model, "--mode", "json", "--no-session", "--no-lsp", "--no-pty", "--no-extensions",
                "--no-rules", "--no-title", "--no-prewalk", "--skills", skill_name, "--tools", ",".join(tools),
                "--thinking", args.thinking, "--max-time", str(args.timeout), "--approval-mode", args.approval_mode,
                "--print", "<controlled-prompt-not-retained>",
            ],
            "credential_like_environment_variable_count_removed": len(removed_env_names),
        }
        _private_json(destination / "launch-policy.json", invocation_update)

        started = time.monotonic()
        actual_exit: int | None = None
        timed_out = False
        abort_reason: str | None = None
        launch_error_type: str | None = None
        raw_stream = b""
        try:
            try:
                process = subprocess.Popen(
                    command,
                    stdin=subprocess.DEVNULL,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.DEVNULL,
                    start_new_session=True,
                    env=child_env,
                )
                actual_exit, timed_out, abort_reason, raw_stream = _watch_process(
                    process, args.model, args.timeout, args.max_stream_bytes
                )
            except OSError as error:
                launch_error_type = type(error).__name__
            summary = inspect_stream(
                raw_stream,
                args.model,
                expected_skill_name=skill_name,
                expected_skill_source=plugin_skill,
            )
            visible_text = summary.pop("visible_text")
        finally:
            # Never persist raw stdout.  This explicit release also avoids
            # retaining private thinking/tool output past evidence reduction.
            raw_stream = b""

        source_after, source_after_error = _manifest_after_run(skill_source.parent)
        plugin_after, plugin_after_error = _manifest_after_run(plugin_skill.parent)
        task_source_after, task_source_after_error = _manifest_after_run(task_source)
        source_unchanged = source_after is not None and source_before["tree_sha256"] == source_after["tree_sha256"]
        plugin_unchanged = plugin_after is not None and plugin_before["tree_sha256"] == plugin_after["tree_sha256"]
        task_source_unchanged = task_source_after is not None and task_source_before["tree_sha256"] == task_source_after["tree_sha256"]
        invocation_passed = (
            actual_exit == 0
            and not timed_out
            and abort_reason is None
            and launch_error_type is None
            and summary["terminal_success"]
            and summary["exact_model_confirmed"]
            and summary["native_skill_protocol"]["passed"]
            and source_unchanged
            and plugin_unchanged
            and task_source_unchanged
        )
        summary.update({
            "process_exit": actual_exit,
            "timed_out": timed_out,
            "identity_or_refusal_abort": abort_reason,
            "launch_error_type": launch_error_type,
            "elapsed_seconds": round(time.monotonic() - started, 3),
            "raw_stream_retained": False,
            "raw_stderr_retained": False,
            "source_binding": {
                "source_unchanged": source_unchanged,
                "isolated_plugin_unchanged": plugin_unchanged,
                "task_fixture_source_unchanged": task_source_unchanged,
                "source_tree_sha256_before": source_before["tree_sha256"],
                "source_tree_sha256_after": source_after["tree_sha256"] if source_after else None,
                "isolated_plugin_tree_sha256_before": plugin_before["tree_sha256"],
                "isolated_plugin_tree_sha256_after": plugin_after["tree_sha256"] if plugin_after else None,
                "independent_manifest_sha256": manifest_record_sha,
                "post_run_manifest_error_types": {
                    "source": source_after_error,
                    "isolated_plugin": plugin_after_error,
                    "task_fixture_source": task_source_after_error,
                },
                "not_an_os_integrity_boundary": True,
            },
            "model_identity": {
                "requested_selector": args.model,
                "local_catalog": catalog,
                "runtime_event_selector_observed": summary["observed_assistant_models"],
                "observable_alias_or_fallback_blocked": bool(summary["exact_model_confirmed"]),
                "provider_server_receipt_observed": False,
                "guarantee_level": "OMP client runtime metadata only; no provider-side signed/server receipt was exposed",
                "must_not_infer_from": ["generated prose", "local configuration", "model catalog", "client-request selector"],
            },
            "transport_run_passed": invocation_passed,
            "behavioral_verdict": "ungraded_by_omp_adapter",
            "run_passed": invocation_passed,
            "residual_limits": [
                "Closed stdin and OMP tool allowlisting are not an operating-system sandbox.",
                "The runner itself does not change global configuration, but OMP may still access or mutate its own global auth/cache state.",
                "Native loading is proven only when the required skill:// read event resolves to the isolated fixture; a keyword in output is not proof.",
                "No raw provider-side model receipt is available in this evidence format.",
                "The adapter does not grade PUA behavioral compliance; pair this with the E1/E2 behavioral grader.",
            ],
        })
        _private_write(destination / "visible-transcript.md", visible_text + ("\n" if visible_text else ""))
        _private_json(destination / "summary.json", summary)
        compact = {
            "run_passed": summary["run_passed"],
            "transport_run_passed": summary["transport_run_passed"],
            "behavioral_verdict": summary["behavioral_verdict"],
            "process_exit": summary["process_exit"],
            "timed_out": summary["timed_out"],
            "identity_or_refusal_abort": summary["identity_or_refusal_abort"],
            "observed_assistant_models": summary["observed_assistant_models"],
            "native_skill_protocol": summary["native_skill_protocol"],
            "run_dir": str(destination),
        }
        print(json.dumps(compact, ensure_ascii=False))
        return 0 if invocation_passed else (125 if abort_reason else (actual_exit if actual_exit not in {None, 0} else 1))
    finally:
        os.umask(old_umask)


if __name__ == "__main__":
    raise SystemExit(main())
