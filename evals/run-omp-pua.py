#!/usr/bin/env python3
"""Bounded OMP runner for a real PUA-skill evaluation.

Default mode is a read-only dry plan.  Only ``--run`` invokes the existing OMP
binary, and that run is deliberately narrow:

* it requires a full ``provider/model`` selector (never a fuzzy alias);
* it copies the requested skill into a new Agent Plugin fixture and requires a
  native ``read(skill://pua)`` proof resolving to that exact copy;
* it starts OMP with closed stdin, a new process group, a timeout and a bounded
  ephemeral JSON stream; and
* it persists redacted visible text and structural evidence, not raw thinking,
  tool-output text, stderr, or environment values. Redaction is best effort,
  not a guarantee against arbitrary secrets repeated in model-visible prose.

This is evidence plumbing, not an operating-system sandbox.  OMP runs as the
current user; restricting its OMP tools and working directory does not prevent a
model with ``bash`` from attempting paths outside the task directory.  Use a
throwaway fixture and omit ``bash`` unless the evaluation needs it.
"""

